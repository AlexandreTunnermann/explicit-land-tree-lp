// Regenerates scripts/verify-copy.mjs: sha256 of every file that is synced into the AI Studio repo.
// Run after any change: node scripts/make-verify.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, SYNC_FILES } from "./sync-files.mjs";

const norm = (s) => s.replace(/\r\n/g, "\n").replace(/\s+$/, "");
const sha = (buf) => createHash("sha256").update(buf).digest("hex");
const sums = {};
for (const f of SYNC_FILES()) {
  if (f === "scripts/verify-copy.mjs") continue;
  const raw = readFileSync(join(ROOT, f));
  sums[f] = sha(f.startsWith("public/images/") ? raw : norm(raw.toString("utf8")));
}
const out = `// Checks that the landing page files are identical to the original build (line endings ignored).
// Run from the project root: node scripts/verify-copy.mjs
// Generated by scripts/make-verify.mjs in github.com/AlexandreTunnermann/explicit-land-tree-lp. Do not edit.
import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";

// Files the CRM connection is expected to change.
const CRM = new Set(["src/lib/crm-tracking.ts", "src/lib/crm-fields.ts", "src/lib/submit-lead.ts"]);
const EXPECTED = ${JSON.stringify(sums, null, 2)};

let bad = 0, crm = 0;
for (const [file, hash] of Object.entries(EXPECTED)) {
  if (!existsSync(file)) { console.log("MISSING  " + file); bad++; continue; }
  const raw = readFileSync(file);
  const data = file.startsWith("public/images/") ? raw : raw.toString("utf8").replace(/\\r\\n/g, "\\n").replace(/\\s+$/, "");
  if (createHash("sha256").update(data).digest("hex") === hash) continue;
  if (CRM.has(file)) { console.log("CRM      " + file + " (changed by the CRM connection: expected)"); crm++; continue; }
  console.log("CHANGED  " + file); bad++;
}
const total = Object.keys(EXPECTED).length;
console.log(bad === 0 ? \`OK: \${total - crm} of \${total} files identical to the original build\${crm ? \`, \${crm} CRM files changed as expected\` : ""}.\` : \`FAILED: \${bad} of \${total} files are missing or different.\`);
process.exit(bad === 0 ? 0 : 1);
`;
writeFileSync(join(ROOT, "scripts/verify-copy.mjs"), out);
console.log("verify-copy.mjs:", Object.keys(sums).length, "files");
